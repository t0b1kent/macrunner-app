import Foundation

/// Переключатели выпуска: что включено в ЭТОЙ сборке для игрока.
///
/// ★★★ ЗАЧЕМ ЭТОТ ФАЙЛ (решение владельца, 15.09.2026).
///   MacRunner пока выходит БЕСПЛАТНО: без лицензии и без оплаты — ранний доступ.
///   Код лицензирования (Services/Licence/Licence.swift, Views/Home/LicenceView.swift)
///   НЕ удалён: он понадобится, когда появятся тарифы, и удалять проверенную
///   криптографию ради того, чтобы через месяц писать её заново, незачем.
///
///   Поэтому он выключен ОДНИМ флагом, а не разбросанными правками. Разложить
///   «бесплатно» по видам значит однажды забыть одно место — и игрок увидит кнопку
///   «Купить», ведущую на страницу, которой на сайте больше нет.
///
///   Пока флаг `false`:
///     · запуск игры не спрашивает лицензию (HomeView.runApp);
///     · раздела «Лицензия» нет в боковой панели (HomeSection.visible);
///     · кнопки покупки не открывают ничего (PurchaseService), а сами они
///       живут только на экранах, до которых игроку не добраться.
///
///   Включить лицензирование = поставить `true` здесь. Больше нигде ничего не трогать.
enum ReleaseFlags {
    static let licensingEnabled = false
}
