/// Что движок умеет СЕГОДНЯ.
///
/// ★★★ ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ЭТО ЗАПИСАНО.
///
///   Временное ограничение, разложенное по текстам интерфейса, превращается во
///   враньё в тот день, когда его снимут, — и никто не помнит, где оно было
///   написано. Владелец, 12.09.2026: «я то разберусь с 32 бита, так что не надо
///   говорить, какой брать».
///
///   Снял ограничение — поменял ОДНУ строку ниже, и всё приложение перестаёт
///   о нём говорить разом: и метка на плитке игры, и предупреждение в карточке,
///   и ответ в «Вопросах».
enum EngineCapabilities {
    /// Запускаем ли мы 32-битные (i386) программы Windows.
    ///
    /// Сегодня нет: для низа адресного пространства нужно разрешение Apple
    /// (`com.apple.security.cs.cross-architecture-support`), и его пока нет.
    /// Появится — поставить `true`, больше нигде ничего не трогать.
    ///
    /// ★ Встроенный движок (выпуск) отвечает сам: строка `architectures` его матрицы
    ///   (`release/engine-sources.json` → ENGINE.json). Сборка разработчика — по-старому.
    static var i386Supported: Bool {
        if let engine = BundledEngine.current {
            return engine.graphics.architecture(.x86)?.status.canLaunch ?? false
        }
        return false
    }
}
